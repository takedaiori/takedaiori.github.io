'use strict'
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const cp = require('node:child_process')
const assert = require('node:assert/strict')
const crypto = require('node:crypto')
const script = path.resolve(__dirname, 'encrypted-build-cache.cjs')
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'blog-cache-test-'))
const key = crypto.randomBytes(32).toString('hex')
const run = mode => cp.execFileSync(process.execPath, [script, mode], { cwd: temp, env: {...process.env, BUILD_CACHE_KEY:key}, stdio:'pipe' })
const data = path.join(temp, '.next/cache/notion/data')
try {
  fs.mkdirSync(data, {recursive:true})
  const entry = (key, updatedAt=Date.now()) => JSON.stringify({ key, updatedAt, value: { text: 'private-test-body' } })
  fs.writeFileSync(path.join(data, 'versioned.json'), entry('page_block_test_1800000000000'))
  fs.writeFileSync(path.join(data, 'metadata.json'), entry('site_metadata'))
  fs.writeFileSync(path.join(data, 'old.json'), entry('page_block_test_1700000000000', Date.now()-7*3600000))
  run('save')
  const blob = path.join(temp, '.build-cache/cache.enc')
  assert.equal(fs.readFileSync(blob).includes(Buffer.from('private-test-body')), false)
  fs.rmSync(path.join(temp, '.next'), {recursive:true})
  run('restore')
  assert.equal(fs.existsSync(path.join(data,'versioned.json')), true)
  assert.equal(fs.existsSync(path.join(data,'metadata.json')), false)
  assert.equal(fs.existsSync(path.join(data,'old.json')), false)
  const corrupted=fs.readFileSync(blob);corrupted[corrupted.length-1]^=1;fs.writeFileSync(blob,corrupted)
  run('restore')
  assert.equal(fs.existsSync(path.join(temp,'.next/cache')),false)
  console.log('Encrypted cache: roundtrip, filtering, age limit, confidentiality and tamper fallback passed')
} finally {fs.rmSync(temp,{recursive:true,force:true})}
